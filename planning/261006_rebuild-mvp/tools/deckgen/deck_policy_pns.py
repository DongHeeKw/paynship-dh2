    def add(self, key, kind, x, cy, text, w=None, h=None, **kw):
        dw, dh = SZ[kind]; w = w or dw; h = h or dh
        self.s.node(kind, x, cy - h / 2, w, h, text, sz=kw.pop('sz', 750), **kw)
        self.n[key] = (x, cy - h / 2, w, h)
    def pt(self, key, side):
        x, y, w, h = self.n[key]
        return {'r': (x + w, y + h / 2), 'l': (x, y + h / 2), 't': (x + w / 2, y), 'b': (x + w / 2, y + h)}[side]
    def e(self, a, sa, b, sb, bend=None, color=None):
        x1, y1 = self.pt(a, sa); x2, y2 = self.pt(b, sb)
        self.s.arrow(x1, y1, x2, y2, bend=bend, color=color)


